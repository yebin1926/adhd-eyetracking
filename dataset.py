# dataset class + collate_fn (pad+mask) reading cached files
#!/usr/bin/env python3
# -*- coding: utf-8 -*-

""" 
Details:
	•	Reads cached per-student files
	•	Returns (sequence, length, label)
	•	collate_fn: pads sequences to max length in batch + creates mask
  
"""

"""
dataset.py
- Dataset class for per-student sequence classification
- Reads cached per-student .npz files generated by preprocess.py
- Collate function pads variable-length segment sequences and creates masks

Expected .npz keys (from preprocess.py):
  - X: float32 array, shape (T, F) where F=444
  - y: int64 scalar (0..3)
  - seg_start_s: float array, shape (T,)
  - seg_end_s: float array, shape (T,)
  - client_id: str
  - group_label: str (optional)
  - test_type: str (optional)

Returns from dataset __getitem__:
  {
    "x": FloatTensor (T, F),
    "y": LongTensor (),
    "mask": BoolTensor (T,),  # all True before padding
    "length": int,
    "client_id": str,
    "seg_start_s": FloatTensor (T,),
    "seg_end_s": FloatTensor (T,)
  }

Collate returns:
  {
    "x": FloatTensor (B, Tmax, F),
    "y": LongTensor (B,),
    "mask": BoolTensor (B, Tmax),  # True where valid
    "lengths": LongTensor (B,),
    "client_ids": List[str],
    "seg_start_s": FloatTensor (B, Tmax),
    "seg_end_s": FloatTensor (B, Tmax)
  }
"""

from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

import numpy as np
import torch
from torch.utils.data import Dataset


# -----------------------------
# Helpers
# -----------------------------
def list_npz_files(cache_dir: str | Path, test_type: Optional[str] = None) -> List[Path]:
    """
    List cached .npz files in cache_dir.
    If test_type is provided, only include files that end with _{test_type}.npz
    (e.g., *_vst.npz, *_dnb.npz).
    """
    cache_dir = Path(cache_dir)
    if not cache_dir.exists():
        raise FileNotFoundError(f"cache_dir not found: {cache_dir}")

    files = sorted(cache_dir.glob("*.npz"))
    if test_type is None:
        return files
    suffix = f"_{test_type}.npz"
    return [p for p in files if p.name.endswith(suffix)]


def _safe_item(v: Any) -> Any:
    """
    np.load may return 0-d arrays for strings; convert them to python scalars.
    """
    if isinstance(v, np.ndarray) and v.shape == ():
        return v.item()
    return v


def _finite_ratio(x: np.ndarray) -> float:
    if x.size == 0:
        return 0.0
    return float(np.isfinite(x).mean())


# -----------------------------
# Dataset
# -----------------------------
@dataclass
class DatasetOptions:
    feature_dim: int = 444
    min_segments: int = 1
    max_segments: Optional[int] = None  # truncate from the front (or back) if needed
    nan_to_num: bool = True
    nan_fill_value: float = 0.0
    drop_if_low_finite_ratio: Optional[float] = None  # e.g., 0.5 to drop bad samples
    in_memory_cache: bool = False  # cache loaded samples in RAM after first load
    sort_by_time: bool = False  # if True, sort segments by seg_start_s before returning


class StudentSequenceDataset(Dataset):
    """
    One item = one student (one .npz file).
    Lazy loads from disk; optional in-memory caching.
    """

    def __init__(
        self,
        cache_dir: str | Path,
        test_type: Optional[str] = None,
        files: Optional[Sequence[str | Path]] = None,
        opts: Optional[DatasetOptions] = None,
    ):
        self.cache_dir = Path(cache_dir)
        self.test_type = test_type
        self.opts = opts or DatasetOptions()

        if files is None:
            self.files: List[Path] = list_npz_files(self.cache_dir, test_type=test_type)
        else:
            self.files = [Path(f) for f in files]

        if len(self.files) == 0:
            raise RuntimeError(f"No .npz files found in {self.cache_dir} (test_type={test_type})")

        # For leakage-free splitting (GroupKFold), we need client_ids without reading X fully.
        self.client_ids: List[str] = []
        self.labels: List[int] = []

        # Optional: cache dict
        self._cache: Dict[int, Dict[str, Any]] = {}

        # Read lightweight metadata once
        self._index_metadata()

        # Filter invalid samples based on opts
        self._apply_filters()

    def _index_metadata(self) -> None:
        self.client_ids = []
        self.labels = []
        for p in self.files:
            with np.load(p, allow_pickle=True) as d:
                cid = _safe_item(d.get("client_id", p.stem))
                y = int(_safe_item(d["y"]))
            self.client_ids.append(str(cid))
            self.labels.append(y)

    def _apply_filters(self) -> None:
        """
        Filter out samples that violate min_segments or finite ratio threshold.
        This loads X only for filtering; still cheap enough for typical dataset sizes.
        """
        keep_files: List[Path] = []
        keep_cids: List[str] = []
        keep_labels: List[int] = []

        for p, cid, y in zip(self.files, self.client_ids, self.labels):
            try:
                with np.load(p, allow_pickle=True) as d:
                    X = d["X"]
                T = int(X.shape[0]) if X.ndim == 2 else 0
                if T < self.opts.min_segments:
                    continue
                if self.opts.drop_if_low_finite_ratio is not None:
                    fr = _finite_ratio(X)
                    if fr < float(self.opts.drop_if_low_finite_ratio):
                        continue
            except Exception:
                # If file is corrupted/unreadable, skip it
                continue

            keep_files.append(p)
            keep_cids.append(cid)
            keep_labels.append(y)

        self.files = keep_files
        self.client_ids = keep_cids
        self.labels = keep_labels

        if len(self.files) == 0:
            raise RuntimeError("After filtering, no usable samples remain.")

    def __len__(self) -> int:
        return len(self.files)

    def __getitem__(self, idx: int) -> Dict[str, Any]:
        if self.opts.in_memory_cache and idx in self._cache:
            return self._cache[idx]

        p = self.files[idx]
        with np.load(p, allow_pickle=True) as d:
            X = d["X"]  # (T,F)
            y = int(_safe_item(d["y"]))
            cid = str(_safe_item(d.get("client_id", p.stem)))

            # segments
            seg_start = d.get("seg_start_s", None)
            seg_end = d.get("seg_end_s", None)

        if not (isinstance(X, np.ndarray) and X.ndim == 2):
            raise ValueError(f"Bad X array in {p}: type={type(X)} shape={getattr(X,'shape',None)}")

        # Optional segment sort by time (should already be ok, but safe)
        if self.opts.sort_by_time and seg_start is not None and isinstance(seg_start, np.ndarray):
            order = np.argsort(seg_start)
            X = X[order]
            if seg_start is not None:
                seg_start = seg_start[order]
            if seg_end is not None:
                seg_end = seg_end[order]

        # Truncate if needed
        if self.opts.max_segments is not None and X.shape[0] > int(self.opts.max_segments):
            # Keep the first max_segments (you can change to keep last if you prefer)
            m = int(self.opts.max_segments)
            X = X[:m]
            if seg_start is not None:
                seg_start = seg_start[:m]
            if seg_end is not None:
                seg_end = seg_end[:m]

        # Ensure feature dimension matches config
        if X.shape[1] != int(self.opts.feature_dim):
            raise ValueError(f"Feature dim mismatch in {p}: got {X.shape[1]}, expected {self.opts.feature_dim}")

        # NaN handling
        if self.opts.nan_to_num:
            X = np.nan_to_num(X, nan=self.opts.nan_fill_value, posinf=self.opts.nan_fill_value, neginf=self.opts.nan_fill_value)

        # Convert to torch
        x_t = torch.from_numpy(X.astype(np.float32))  # (T,F)
        y_t = torch.tensor(y, dtype=torch.long)
        T = x_t.shape[0]
        mask_t = torch.ones((T,), dtype=torch.bool)

        # seg arrays
        if seg_start is None or not isinstance(seg_start, np.ndarray):
            seg_start_t = torch.zeros((T,), dtype=torch.float32)
        else:
            seg_start_t = torch.from_numpy(seg_start.astype(np.float32))

        if seg_end is None or not isinstance(seg_end, np.ndarray):
            seg_end_t = torch.zeros((T,), dtype=torch.float32)
        else:
            seg_end_t = torch.from_numpy(seg_end.astype(np.float32))

        out = {
            "x": x_t,
            "y": y_t,
            "mask": mask_t,
            "length": int(T),
            "client_id": cid,
            "seg_start_s": seg_start_t,
            "seg_end_s": seg_end_t,
            "path": str(p),
        }

        if self.opts.in_memory_cache:
            self._cache[idx] = out

        return out


# -----------------------------
# Collate function (pad + mask)
# -----------------------------
def collate_student_batch(batch: List[Dict[str, Any]]) -> Dict[str, Any]:
    """
    Pads sequences to max length in batch.
    Returns tensors suitable for BiGRU + attention with masks.
    """
    if len(batch) == 0:
        raise ValueError("Empty batch")

    lengths = torch.tensor([b["length"] for b in batch], dtype=torch.long)
    B = len(batch)
    Tmax = int(lengths.max().item())
    F = int(batch[0]["x"].shape[1])

    x_pad = torch.zeros((B, Tmax, F), dtype=torch.float32)
    mask = torch.zeros((B, Tmax), dtype=torch.bool)
    y = torch.zeros((B,), dtype=torch.long)

    seg_start_pad = torch.zeros((B, Tmax), dtype=torch.float32)
    seg_end_pad = torch.zeros((B, Tmax), dtype=torch.float32)

    client_ids: List[str] = []

    for i, b in enumerate(batch):
        x_i = b["x"]
        T = x_i.shape[0]
        x_pad[i, :T] = x_i
        mask[i, :T] = True
        y[i] = b["y"]
        client_ids.append(b["client_id"])

        # optional segment times
        seg_start = b.get("seg_start_s", None)
        seg_end = b.get("seg_end_s", None)
        if isinstance(seg_start, torch.Tensor) and seg_start.numel() == T:
            seg_start_pad[i, :T] = seg_start
        if isinstance(seg_end, torch.Tensor) and seg_end.numel() == T:
            seg_end_pad[i, :T] = seg_end

    return {
        "x": x_pad,                 # (B,Tmax,F)
        "y": y,                     # (B,)
        "mask": mask,               # (B,Tmax) True for valid
        "lengths": lengths,         # (B,)
        "client_ids": client_ids,   # list[str]
        "seg_start_s": seg_start_pad,  # (B,Tmax)
        "seg_end_s": seg_end_pad,      # (B,Tmax)
    }


# -----------------------------
# Optional: split helper (no leakage)
# -----------------------------
def get_groups_and_labels(dataset: StudentSequenceDataset) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Returns (indices, labels, groups) arrays for GroupKFold.
    groups = client_id (student id), so no leakage across folds.
    """
    idx = np.arange(len(dataset), dtype=int)
    y = np.asarray(dataset.labels, dtype=int)
    groups = np.asarray(dataset.client_ids, dtype=object)
    return idx, y, groups